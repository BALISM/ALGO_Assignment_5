"""
q4_theory.py  -  Question 4 : Theoretical Analysis of Prim's & Kruskal's Algorithms
CS2009 Design and Analysis of Algorithms  -  Assignment 4

Part (a): Prove that for any MST T of G, there exists an edge ordering for
          Kruskal's algorithm that makes it output exactly T.

Part (b): Fast implementations of Prim and Kruskal when edge weights are
          bounded integers.
          (b-i)  Prim  - weights in {1 .. |V|} and {1 .. W}
          (b-ii) Kruskal - same ranges
"""

import sys
import os


def header(title, lines, width=78):
    lines.append("=" * width)
    lines.append(title)
    lines.append("=" * width)


def sub(title, lines):
    lines.append("")
    lines.append("-" * 60)
    lines.append(title)
    lines.append("-" * 60)


def build_theory():
    lines = []

    lines.append("Q4 : THEORETICAL ANALYSIS  -  PRIM'S AND KRUSKAL'S ALGORITHMS")
    lines.append("CS2009 Design and Analysis of Algorithms  -  Assignment 4")
    lines.append("")

    # =========================================================================
    # Part (a)
    # =========================================================================
    header("Q4 (a)  PROOF: Any MST T can be produced by Kruskal's Algorithm", lines)
    lines.append("")
    lines.append("Claim")
    lines.append("-----")
    lines.append("  Let G = (V, E, w) be a weighted undirected graph and let T be any")
    lines.append("  minimum spanning tree of G.  Then there exists a total ordering of")
    lines.append("  the edges of E (consistent with non-decreasing weights) such that")
    lines.append("  Kruskal's algorithm, using that ordering, outputs exactly T.")
    lines.append("")
    lines.append("Background: how Kruskal's algorithm processes ties")
    lines.append("--------------------------------------------------")
    lines.append("  Kruskal's algorithm processes edges in non-decreasing weight order.")
    lines.append("  When multiple edges have the same weight, the algorithm may choose")
    lines.append("  among them in any order.  Different orderings among tied edges can")
    lines.append("  produce different spanning trees, all of which are MSTs (they all")
    lines.append("  have the same total weight).")
    lines.append("")
    lines.append("Proof")
    lines.append("-----")
    lines.append("  Let T be an arbitrary MST of G.  We construct an edge ordering sigma")
    lines.append("  such that Kruskal(sigma) = T.")
    lines.append("")
    lines.append("  Step 1 - Partition the edges by weight.")
    lines.append("    Let w_1 < w_2 < ... < w_k be the distinct edge weights.  Let")
    lines.append("    E_i  = { e in E : w(e) = w_i }  and")
    lines.append("    T_i  = { e in T : w(e) = w_i } (the MST edges at weight w_i).")
    lines.append("    By the MST cycle-cut property, T_i is a subset of E_i.")
    lines.append("")
    lines.append("  Step 2 - Order edges within each weight class.")
    lines.append("    Within E_i, list the edges of T_i FIRST (in any order among themselves),")
    lines.append("    followed by the edges of E_i \\ T_i (in any order).")
    lines.append("    Concatenating these ordered groups for i = 1, 2, ..., k gives sigma.")
    lines.append("")
    lines.append("  Step 3 - Show Kruskal(sigma) = T.")
    lines.append("    Kruskal processes edges in the order sigma.  We track the DSU state")
    lines.append("    after processing each weight class.")
    lines.append("")
    lines.append("    Invariant (maintained by induction on weight class i):")
    lines.append("      After processing all edges of weight <= w_i, the edges accepted by")
    lines.append("      Kruskal are exactly the edges of T with weight <= w_i, i.e.,")
    lines.append("      T_1 union T_2 union ... union T_i.")
    lines.append("")
    lines.append("    Base case (i = 0): trivially true (empty set).")
    lines.append("")
    lines.append("    Inductive step (weight class w_i):")
    lines.append("      Assume the invariant holds after weight class w_{i-1}.")
    lines.append("      We process E_i in the order: T_i edges first, then E_i \\ T_i edges.")
    lines.append("")
    lines.append("      (a) Each edge e = (u, v) in T_i is considered.")
    lines.append("          Since T is a spanning tree and the edges accepted so far form")
    lines.append("          a forest that is a subgraph of T, the components of the current")
    lines.append("          DSU are exactly the connected components of the subgraph")
    lines.append("          T[V, T_1 union ... union T_{i-1}].  Every edge in T_i connects two")
    lines.append("          different components in that forest (otherwise T would contain")
    lines.append("          a cycle, contradicting that T is a tree).  Therefore DSU.find(u)")
    lines.append("          != DSU.find(v), so Kruskal ACCEPTS e.  After processing all of")
    lines.append("          T_i, the accepted edges are T_1 union ... union T_i.")
    lines.append("")
    lines.append("      (b) Each edge e = (u, v) in E_i \\ T_i is considered.")
    lines.append("          Adding e to T would create a cycle C in T.  All edges of C")
    lines.append("          lie in T; those with weight < w_i were accepted in earlier")
    lines.append("          rounds, and those with weight w_i are in T_i (all accepted in")
    lines.append("          step (a) above).  Therefore u and v are already connected in")
    lines.append("          the current DSU forest, so Kruskal REJECTS e.")
    lines.append("")
    lines.append("      After processing all of E_i the invariant holds for class i.")
    lines.append("")
    lines.append("    By induction the invariant holds for all i.  After processing all")
    lines.append("    edges the accepted set is T_1 union ... union T_k = T.  Hence Kruskal(sigma)")
    lines.append("    outputs exactly T.                                              QED")
    lines.append("")
    lines.append("Corollary")
    lines.append("---------")
    lines.append("  Every MST of G is a possible output of Kruskal's algorithm for some")
    lines.append("  tie-breaking rule.  Equivalently, the set of Kruskal outputs (over all")
    lines.append("  tie-breaking rules) is exactly the set of all MSTs of G.")

    # =========================================================================
    # Part (b)
    # =========================================================================
    header("Q4 (b)  FAST IMPLEMENTATIONS WITH BOUNDED INTEGER WEIGHTS", lines)
    lines.append("")
    lines.append("We consider two ranges of integer weights:")
    lines.append("  (R1) weights in { 1, 2, ..., |V| }  -- range proportional to V")
    lines.append("  (R2) weights in { 1, 2, ..., W  }   -- constant range W")
    lines.append("")
    lines.append("The key observation is that INTEGER edge weights allow COUNTING SORT")
    lines.append("(or RADIX SORT) instead of comparison-based sorting, breaking the")
    lines.append("O(E log E) comparison barrier.")
    lines.append("")

    # ------- Prim -------
    sub("Q4 (b-i)  PRIM'S ALGORITHM WITH BOUNDED INTEGER WEIGHTS", lines)
    lines.append("")
    lines.append("Standard Prim (binary heap): O((V + E) log V).")
    lines.append("")
    lines.append("Case R1: weights in { 1 .. |V| }")
    lines.append("  Replace the binary min-heap with a VAN EMDE BOAS TREE (vEB tree)")
    lines.append("  supporting insert, decrease-key, and extract-min in O(log log V)")
    lines.append("  amortised time when keys are integers in { 0 .. V-1 }.")
    lines.append("")
    lines.append("  Time with vEB tree: O((V + E) log log V)")
    lines.append("")
    lines.append("  Alternative -- BUCKET QUEUE (also called a DIAL's queue):")
    lines.append("  Maintain an array of |V| buckets indexed by edge weight.")
    lines.append("  insert and decrease-key: O(1)   (write to bucket)")
    lines.append("  extract-min: O(|V|) worst case (scan buckets), but O(1) amortised")
    lines.append("               if the current minimum pointer advances monotonically.")
    lines.append("")
    lines.append("  Time with Bucket Queue: O(V + E + |V|) = O(V + E)")
    lines.append("  (the |V| term arises from scanning at most |V| buckets total).")
    lines.append("")
    lines.append("  Therefore, with weights in { 1 .. |V| }:")
    lines.append("      PRIM can run in O(V + E)  using a bucket-queue priority queue.")
    lines.append("")
    lines.append("Case R2: weights in { 1 .. W } for constant W")
    lines.append("  The bucket queue now has only W buckets.")
    lines.append("  extract-min scans at most W buckets: O(W) = O(1) amortised.")
    lines.append("  Total time: O(V + E + W) = O(V + E)  (W is a constant).")
    lines.append("")
    lines.append("  Therefore, with weights in { 1 .. W } (W constant):")
    lines.append("      PRIM can run in O(V + E).")
    lines.append("")
    lines.append("Summary for Prim")
    lines.append("  +--------------------------------+---------------------------+")
    lines.append("  | Weight range                   | Best achievable time      |")
    lines.append("  +--------------------------------+---------------------------+")
    lines.append("  | Arbitrary reals / no bound     | O((V+E) log V)  [binary heap] |")
    lines.append("  | Integers in { 1 .. |V| }       | O(V + E)        [bucket queue] |")
    lines.append("  | Integers in { 1 .. W }, W=const| O(V + E)        [bucket queue] |")
    lines.append("  +--------------------------------+---------------------------+")

    # ------- Kruskal -------
    sub("Q4 (b-ii)  KRUSKAL'S ALGORITHM WITH BOUNDED INTEGER WEIGHTS", lines)
    lines.append("")
    lines.append("Standard Kruskal (comparison sort + DSU): O(E log E).")
    lines.append("")
    lines.append("The bottleneck is edge sorting.  With integer weights we can use")
    lines.append("non-comparison sorting to break the Omega(E log E) comparison barrier.")
    lines.append("")
    lines.append("Case R1: weights in { 1 .. |V| }")
    lines.append("  Use COUNTING SORT to sort E edge weights in O(E + |V|) time.")
    lines.append("  DSU processes E edges in O(E alpha(V)) ~ O(E) time.")
    lines.append("")
    lines.append("  Total time: O(E + V)   (counting sort dominates over DSU).")
    lines.append("")
    lines.append("Case R2: weights in { 1 .. W } for constant W")
    lines.append("  Counting sort with W buckets: O(E + W) = O(E)  (W is constant).")
    lines.append("  DSU: O(E alpha(V)) ~ O(E).")
    lines.append("")
    lines.append("  Total time: O(E).")
    lines.append("")
    lines.append("  Note: O(E) is essentially optimal since merely reading the edge list")
    lines.append("  requires Omega(E) time.")
    lines.append("")
    lines.append("Summary for Kruskal")
    lines.append("  +--------------------------------+---------------------------+")
    lines.append("  | Weight range                   | Best achievable time      |")
    lines.append("  +--------------------------------+---------------------------+")
    lines.append("  | Arbitrary reals / no bound     | O(E log E)   [comparison sort] |")
    lines.append("  | Integers in { 1 .. |V| }       | O(E + V)     [counting sort]   |")
    lines.append("  | Integers in { 1 .. W }, W=const| O(E)         [counting sort]   |")
    lines.append("  +--------------------------------+---------------------------+")
    lines.append("")

    lines.append("Comparison: Prim vs Kruskal with Bounded Weights")
    lines.append("-------------------------------------------------")
    lines.append("")
    lines.append("  Weights in { 1 .. |V| }:")
    lines.append("    Prim   : O(V + E)   (bucket queue)")
    lines.append("    Kruskal: O(V + E)   (counting sort + DSU)")
    lines.append("    Both achieve the same O(V + E) time -- essentially linear.")
    lines.append("")
    lines.append("  Weights in { 1 .. W } (constant W):")
    lines.append("    Prim   : O(V + E)   (bucket queue with W buckets)")
    lines.append("    Kruskal: O(E)       (counting sort + DSU, O(E) dominates)")
    lines.append("    Kruskal has a slight edge because V is absorbed by E when the")
    lines.append("    graph is connected (E >= V-1), so both are effectively O(E).")
    lines.append("")
    lines.append("  Space for both algorithms remains O(V + E) in the adjacency-list model.")
    lines.append("")
    lines.append("Conclusion")
    lines.append("----------")
    lines.append("  Bounded integer edge weights allow linear-time (or near-linear)")
    lines.append("  MST construction using non-comparison sorting for Kruskal and")
    lines.append("  bucket-queue priority queues for Prim.  When weights are integers")
    lines.append("  in { 1 .. W } for a constant W, both Prim and Kruskal run in O(V + E)")
    lines.append("  which is essentially optimal for sparse graphs.")

    return "\n".join(lines)


def main():
    text = build_theory()
    print(text)
    os.makedirs("outputs", exist_ok=True)
    with open("outputs/q4_output.txt", "w", encoding="utf-8") as f:
        f.write(text + "\n")


if __name__ == "__main__":
    main()
